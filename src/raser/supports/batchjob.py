"""IHEP cluster job planning and submission."""

from __future__ import annotations

import grp
import os
import shlex
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

from raser.supports.paths import REPO_ROOT
from raser.supports.paths import project_path


# hep_sub copies the login environment to the worker, which has no display.
_WORKER_UNSET = (
    "DISPLAY",
    "XAUTHORITY",
    "XDG_RUNTIME_DIR",
    "APPTAINERENV_DISPLAY",
    "APPTAINERENV_XAUTHORITY",
    "SINGULARITYENV_DISPLAY",
    "SINGULARITYENV_XAUTHORITY",
)
_WORKER_BIND_VARIABLES = (
    "APPTAINER_BIND",
    "APPTAINER_BINDPATH",
    "SINGULARITY_BIND",
    "SINGULARITY_BINDPATH",
    "BINDPATH",
    "RASER_SIF_BIND",
    "RASER_SIF_EXTRA_BINDS",
)


@dataclass(frozen=True)
class ClusterJobPlan:
    job_file: Path
    worker_command: tuple[str, ...]
    submit_command: tuple[str, ...]

    def as_dict(self) -> dict:
        return {
            "job_file": str(self.job_file),
            "worker_command": list(self.worker_command),
            "submit_command": list(self.submit_command),
        }


def job_dir(destination_subfolder):
    return project_path(destination_subfolder, "jobs")


def _tokens(command: str | Sequence[str]) -> tuple[str, ...]:
    return tuple(
        shlex.split(command) if isinstance(command, str) else map(str, command)
    )


def worker_script(worker_command: Sequence[str], route: str | None) -> str:
    """Return a job script that activates the route again on the worker."""
    setup = f"env/setup_cvmfs.sh {shlex.quote(route)}" if route else "env/setup.sh"
    lines = [
        "#!/bin/bash",
        "# Generated by raser for a cluster worker, which runs without X11.",
        'raser_x11_sources=(/tmp/.X11-unix /tmp/.X11-unix/ "$HOME/.Xauthority"',
        '    "${XDG_RUNTIME_DIR:-}"',
        '    "${XAUTHORITY:-}" "${APPTAINERENV_XAUTHORITY:-}" "${SINGULARITYENV_XAUTHORITY:-}")',
        "unset " + " ".join(_WORKER_UNSET),
        "for raser_bind_name in " + " ".join(_WORKER_BIND_VARIABLES) + "; do",
        '    [ -n "${!raser_bind_name}" ] || continue',
        '    IFS=, read -r -a raser_binds <<< "${!raser_bind_name}"',
        "    raser_filtered_binds=",
        '    for raser_bind in "${raser_binds[@]}"; do',
        '        for raser_x11_source in "${raser_x11_sources[@]}"; do',
        '            [ "${raser_bind%%:*}" = "$raser_x11_source" ] && continue 2',
        "        done",
        "        raser_filtered_binds=${raser_filtered_binds:+$raser_filtered_binds,}$raser_bind",
        "    done",
        '    export "$raser_bind_name=$raser_filtered_binds"',
        "done",
        f"cd {shlex.quote(str(REPO_ROOT))} || exit 1",
        f". {setup} || exit $?",
        shlex.join(worker_command),
    ]
    return "\n".join(lines)


def plan_job(destination_subfolder, command, batch_level, *, group=None):
    if batch_level <= 0:
        raise ValueError("Batch memory level must be positive")
    command_tokens = _tokens(command)
    if not command_tokens:
        raise ValueError("Batch worker command must contain tokens")
    group_name = group or grp.getgrgid(os.stat(".").st_gid)[0]
    memory_mb = 8000 * batch_level
    directory = job_dir(destination_subfolder)
    command_name = "_".join(command_tokens).replace("/", "_")
    job_file = directory / f"{command_name}.job"
    worker = ("raser", *command_tokens)
    submit = (
        "hep_sub",
        "-o",
        str(directory),
        "-e",
        str(directory),
        str(job_file),
        "-mem",
        str(memory_mb),
        "-g",
        group_name,
    )
    return ClusterJobPlan(job_file, worker, submit)


def main(destination_subfolder, command, batch_level, is_test=False):
    plan = plan_job(destination_subfolder, command, batch_level)
    script = worker_script(
        plan.worker_command, os.environ.get("RASER_ENV_ROUTE") or None
    )
    if is_test:
        print(f"# {plan.job_file}")
        print(script)
        print(shlex.join(plan.submit_command))
        return plan
    gen_job(plan.job_file, script)
    submit_job(plan)
    return plan


def gen_job(jobfile_name, run_code):
    path = Path(jobfile_name)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(str(run_code) + "\n", encoding="utf-8")
    path.chmod(0o755)
    return path


def submit_job(plan: ClusterJobPlan):
    queue = os.environ.get("RASER_SUBMIT_QUEUE")
    if queue:
        # The SIF has no scheduler client; raser() on the host submits the queue.
        with open(queue, "a", encoding="utf-8") as stream:
            stream.write(shlex.join(plan.submit_command) + "\n")
        return
    subprocess.run(plan.submit_command, shell=False, check=True)


def run_cmd(command, is_test=False):
    command_tokens = _tokens(command)
    if is_test:
        print(shlex.join(command_tokens))
        return command_tokens
    subprocess.run(command_tokens, shell=False, check=True)
    return command_tokens
